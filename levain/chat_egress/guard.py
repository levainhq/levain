"""The denied-address table srt's resolved-address guard is configured with, GENERATED and TRANSLATED from
`levain.broker.front`, and the decider's own address wall.

Design §3.8.5(o) C-3 (rev 15.11), rows R15-12-B4, R15-14-2, R15-17-3, R9-A6. Two checks hold every dial:
  1. the decider (FIRST): every resolved answer through `front.refused_address`; ANY refused -> wall
     `non_public_address` before R-1 .. R-10 run (`address_wall`). It alone keeps the rules that are not ranges: the
     scope-id refusal and the IPv4-mapped refusal.
  2. srt's guard at dial: `deniedResolvedAddresses` = this table, so a rebinding between the decider's lookup and the
     dial meets it (srt resolves once and dials the address that passed).

The table is `front._REFUSED_NETS` minus `::ffff:0:0/96`, PLUS every range the pinned Python's `ipaddress` treats as
non-global that front's ranges do not already contain. The one translation: `::ffff:0:0/96` is dropped because node's
`BlockList` (srt's guard) matches an IPv4 address against IPv4-mapped rules too, so that range verbatim refuses EVERY
IPv4 answer (measured: ROUND3 B4 run B); srt instead judges a mapped answer by the IPv4 rules, i.e. by the address it
is dialed as. `expected_dial_refusal` states that translation for the per-address test.

The Python non-global ranges are taken whole (`_private_networks`, without carving out `_private_networks_exceptions`):
srt may refuse more than front, never less, so the few global anycast / ORCHID blocks inside a non-global supernet
are refused at dial too (an availability edge, never a reach).

`generate_table()` rendered by `render_table` is what TABLE_PATH must hold; the committed file is the reviewed artifact,
regenerated byte-for-byte only under PINNED_PYTHON (`scripts/gen_denied_table.py`).

`load_table()` is the launch's read, and it checks COVERAGE, not only shape: every network of front's refused set (the
dropped range aside) and of the RUNNING Python's `python_non_global()` must lie inside one of the table's ranges, or it
raises `DeniedTableError` and the launch is refused. So a table missing a range, or a newer Python that marks a new
range non-global, fails closed in an installed runtime too, not only in the test suite.
"""

from __future__ import annotations

import ipaddress
import json
import sys
from pathlib import Path
from typing import Iterable

from levain.broker import front

TABLE_PATH = Path(__file__).resolve().parent / "denied_table.json"
TABLE_FORMAT = "levain-chat-egress-denied/1"
#: The Python whose `ipaddress` tables the committed artifact was generated under (R15-17-3: "under a pinned Python
#: version (the test pins it)"). Moving it is a regeneration plus a review of the diff.
PINNED_PYTHON = "3.12"
#: Compared as NETWORKS, never as strings: Python 3.12 spells this one `::ffff:0.0.0.0/96`.
DROPPED = ("::ffff:0:0/96",)
_DROPPED_NETS = frozenset(ipaddress.ip_network(d) for d in DROPPED)
_MAPPED = ipaddress.ip_network("::ffff:0:0/96")
_SHARED = ipaddress.ip_network("100.64.0.0/10")   # not global and not private in `ipaddress`
_FIELDS = {"format", "python", "source", "dropped", "ranges"}

Net = ipaddress.IPv4Network | ipaddress.IPv6Network


class DeniedTableError(ValueError):
    """The denied table cannot be handed to srt: malformed, or not covering a range Levain refuses (front's set or
    the running Python's non-global ranges), or this Python's `ipaddress` tables cannot be read. The launch is
    refused on it; there is no fallback table."""


def python_non_global() -> list[Net]:
    """The running Python's non-global ranges, the IPv4-mapped one aside: its private tables (v4 and v6) whole, plus
    100.64.0.0/10. Reads `ipaddress`'s module constants, which is why the Python is pinned."""
    nets: list[Net] = [_SHARED]
    try:
        for consts in (ipaddress.IPv4Address._constants, ipaddress.IPv6Address._constants):   # type: ignore[attr-defined]
            got = list(consts._private_networks)
            if not got or not all(isinstance(n, (ipaddress.IPv4Network, ipaddress.IPv6Network)) for n in got):
                raise TypeError("not a list of networks")
            nets += got
    except (AttributeError, TypeError) as e:
        raise DeniedTableError(
            f"Python {sys.version_info[0]}.{sys.version_info[1]}: ipaddress's private-network tables "
            f"(`_constants._private_networks`) moved or changed shape ({e}); the denied table's coverage cannot be "
            "derived, so it is refused. Update guard.python_non_global for this Python.") from None
    return [n for n in nets if not (n.version == 6 and n.subnet_of(_MAPPED))]


def _covered(n: Net, by: Iterable[Net]) -> bool:
    return any(n.version == b.version and n.subnet_of(b) for b in by)


def generate_table() -> dict:
    """The table, derived now from `front._REFUSED_NETS` and the running Python."""
    base = [n for n in front._REFUSED_NETS if n not in _DROPPED_NETS]
    added: list[Net] = []
    for n in python_non_global():
        if not _covered(n, base + added):
            added.append(n)
    ranges = [str(n) for n in base] + [str(n) for n in sorted(added, key=lambda n: (n.version, n))]
    return {
        "format": TABLE_FORMAT,
        "python": f"{sys.version_info[0]}.{sys.version_info[1]}",
        "source": "levain.broker.front._REFUSED_NETS minus the dropped ranges, then the ipaddress non-global "
                  "ranges of the named Python not already contained (generated by scripts/gen_denied_table.py)",
        "dropped": list(DROPPED),
        "ranges": ranges,
    }


def render_table(table: dict) -> str:
    """The committed file's exact text."""
    head = {k: table[k] for k in ("format", "python", "source", "dropped")}
    lines = ",\n".join(f"  {json.dumps(r)}" for r in table["ranges"])
    body = json.dumps(head, indent=1)[:-2]
    return f"{body},\n \"ranges\": [\n{lines}\n ]\n}}\n"


def validate_table(table: object) -> tuple[str, ...]:
    """The ranges of a well-formed table, or ValueError: the fields exactly, the format, each range a strict CIDR in
    its canonical spelling, no duplicate, no dropped range."""
    if not isinstance(table, dict) or set(table) != _FIELDS:
        raise ValueError("denied table: fields")
    if table["format"] != TABLE_FORMAT:
        raise ValueError(f"denied table: format {table['format']!r}")
    ranges = table["ranges"]
    if not isinstance(ranges, list) or not ranges:
        raise ValueError("denied table: ranges")
    for r in ranges:
        try:
            ok = isinstance(r, str) and str(ipaddress.ip_network(r, strict=True)) == r
        except ValueError:
            ok = False
        if not ok:
            raise ValueError(f"denied table: range {r!r}")
    if len(set(ranges)) != len(ranges):
        raise ValueError("denied table: duplicate range")
    if any(ipaddress.ip_network(r) in _DROPPED_NETS for r in ranges):
        raise ValueError("denied table: a dropped range is present")
    return tuple(ranges)


def required_networks() -> list[Net]:
    """What a denied table must cover, now: front's refused set without the dropped range, and the running Python's
    non-global ranges."""
    return [n for n in front._REFUSED_NETS if n not in _DROPPED_NETS] + python_non_global()


def coverage_gaps(ranges: Iterable[str]) -> list[Net]:
    """The required networks that no single range of `ranges` contains (network containment, never a string
    compare), in required order, each once."""
    have = [ipaddress.ip_network(r) for r in ranges]
    gaps: list[Net] = []
    for n in required_networks():
        if n not in gaps and not _covered(n, have):
            gaps.append(n)
    return gaps


def load_table(path: Path = TABLE_PATH) -> tuple[str, ...]:
    """The committed table's ranges (what the launch hands srt as `deniedResolvedAddresses`), validated in shape AND
    in coverage: DeniedTableError, refusing the launch, when it is malformed or a required network is not covered."""
    try:
        ranges = validate_table(json.loads(path.read_text()))
    except DeniedTableError:
        raise
    except ValueError as e:   # json.JSONDecodeError is one
        raise DeniedTableError(str(e)) from None
    gaps = coverage_gaps(ranges)
    if gaps:
        raise DeniedTableError(f"denied table {path} does not cover: {', '.join(str(n) for n in gaps)}")
    return ranges


def table_problems(table: dict) -> list[str]:
    """Why `table` is not a sound denied table for this Python: malformed, a dropped range present, or a range the
    generator emits now missing from it. [] when sound. (Extra ranges are allowed: srt may refuse more.)"""
    probs: list[str] = []
    if isinstance(table, dict) and isinstance(table.get("ranges"), list):
        probs += [f"dropped range present: {r}" for r in table["ranges"] if _is_dropped(r)]
    try:
        have = set(validate_table(table))
    except ValueError as e:
        return probs or [str(e)]
    probs += [f"missing range: {r}" for r in generate_table()["ranges"] if r not in have]
    return probs


def expected_dial_refusal(addr: str) -> bool:
    """Whether Levain refuses `addr` AT DIAL, i.e. what srt's guard must refuse: `front.refused_address(addr)`, with
    the table's one translation: an IPv4-mapped answer is judged by the IPv4 address it is dialed as (front refuses
    every mapped answer, and the decider applies that FIRST, at its own lookup)."""
    try:
        ip = ipaddress.ip_address(addr.split("%", 1)[0])
    except ValueError:
        return front.refused_address(addr) is not None
    if ip.version == 6 and ip.ipv4_mapped is not None and "%" not in addr:
        return front.refused_address(str(ip.ipv4_mapped)) is not None
    return front.refused_address(addr) is not None


def address_wall(answers: Iterable[str]) -> str | None:
    """The decider's C-3 wall over one resolution's answers: "non_public_address" if ANY answer is refused by
    `front.refused_address` (an unparseable or scoped answer included), else None. ValueError for no answer: a failed
    resolution is the caller's to deny, not an address verdict."""
    answers = list(answers)
    if not answers:
        raise ValueError("no answer to judge")
    return "non_public_address" if any(front.refused_address(a) is not None for a in answers) else None


def _is_dropped(r: object) -> bool:
    try:
        return isinstance(r, str) and ipaddress.ip_network(r, strict=False) in _DROPPED_NETS
    except ValueError:
        return False
