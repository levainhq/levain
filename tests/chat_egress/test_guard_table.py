"""CH-D2 S2: the denied-address table, generated and translated (the Python half; srt's verdicts are in
test_guard_srt.py).

Rows: R15-14-2 (generated from `front._REFUSED_NETS`, without `::ffff:0:0/96`), R15-17-3 (plus the pinned Python's
non-global ranges; a committed artifact; red on any dropped range), R9-A6 (the decider's address wall uses
`front.refused_address`), R15-12-B4 (the table is generated, never hand-copied).
"""

from __future__ import annotations

import copy
import ipaddress
import json
import sys

import pytest

from levain.broker import front
from levain.chat_egress import guard


def committed() -> dict:
    return json.loads(guard.TABLE_PATH.read_text())


# --- R15-14-2: generated from front, translated -----------------------------------------------------------------

def test_r15_14_2_generator_reads_front(monkeypatch):
    """Derived, not copied: a range added to front's table appears in the generated one."""
    extra = ipaddress.ip_network("9.9.9.0/24")
    monkeypatch.setattr(front, "_REFUSED_NETS", front._REFUSED_NETS + (extra,))
    assert "9.9.9.0/24" in guard.generate_table()["ranges"]


def test_r15_14_2_mapped_range_is_dropped():
    t = guard.generate_table()
    mapped = ipaddress.ip_network("::ffff:0:0/96")
    assert not any(ipaddress.ip_network(r) == mapped for r in t["ranges"])   # as networks: 3.12 spells it ::ffff:0.0.0.0/96
    assert t["dropped"] == ["::ffff:0:0/96"]
    assert ipaddress.ip_network("::ffff:0:0/96") in front._REFUSED_NETS   # it is dropped, not absent at the source


def test_r15_14_2_every_front_range_but_the_mapped_one_is_present():
    ranges = set(guard.generate_table()["ranges"])
    for net in front._REFUSED_NETS:
        if net != ipaddress.ip_network("::ffff:0:0/96"):
            assert str(net) in ranges


# --- R15-17-3: plus Python's non-global ranges, under a pinned Python ---------------------------------------------

def test_r15_17_3_python_non_global_ranges_are_covered():
    """Every range the running Python's `ipaddress` treats as non-global (its private tables minus their
    exceptions, plus 100.64.0.0/10), the IPv4-mapped one aside, is inside a generated range."""
    nets = [ipaddress.ip_network(r) for r in guard.generate_table()["ranges"]]
    for r in guard.python_non_global():
        assert any(r.version == n.version and r.subnet_of(n) for n in nets), r


def test_r15_17_3_an_address_only_is_global_refuses_is_in_the_table():
    """2001:2::1 is in Python's 2001::/23 (not global) and outside front's 2001::/32: only the `is_global`
    catch-all refuses it in front, so only the generator's addition puts it in srt's table."""
    a = ipaddress.ip_address("2001:2::1")
    assert front.refused_address(str(a)) == "not-global"
    assert not any(a.version == n.version and a in n for n in front._REFUSED_NETS)
    assert any(a in ipaddress.ip_network(r) for r in guard.generate_table()["ranges"] if ":" in r)


def test_r15_17_3_generated_ranges_are_non_global_at_both_ends():
    for r in guard.generate_table()["ranges"]:
        n = ipaddress.ip_network(r)
        for a in (n[0], n[-1]):
            assert front.refused_address(str(a)) is not None, (r, a)


def test_r15_17_3_python_is_pinned():
    t = committed()
    assert t["python"] == guard.PINNED_PYTHON
    assert guard.PINNED_PYTHON == "3.12"


@pytest.mark.skipif(f"{sys.version_info[0]}.{sys.version_info[1]}" != guard.PINNED_PYTHON,
                    reason="the committed table is regenerated byte-for-byte only under the pinned Python")
def test_r15_17_3_committed_table_is_the_generated_one():
    assert guard.TABLE_PATH.read_text() == guard.render_table(guard.generate_table())


def test_r15_17_3_committed_table_covers_this_python():
    """Under any Python (CI runs more than the pinned one): no range this Python treats as non-global is missing
    from the committed table. A newer Python that adds one makes this red until the table is regenerated."""
    assert guard.table_problems(committed()) == []


def test_r15_17_3_committed_table_drops_no_range():
    t = committed()
    missing = set(guard.generate_table()["ranges"]) - set(t["ranges"])
    if f"{sys.version_info[0]}.{sys.version_info[1]}" == guard.PINNED_PYTHON:
        assert missing == set()
    else:   # the pinned table may differ from a newer Python's by non-global additions only
        assert all(ipaddress.ip_network(m) not in front._REFUSED_NETS for m in missing)


@pytest.mark.parametrize("i", range(len(json.loads(guard.TABLE_PATH.read_text())["ranges"])))
def test_r15_17_3_hand_edited_copy_with_a_dropped_range_is_red(i):
    t = copy.deepcopy(committed())
    dropped = t["ranges"].pop(i)
    probs = guard.table_problems(t)
    assert probs and any(dropped in p for p in probs), probs


@pytest.mark.parametrize("spelling", ["::ffff:0:0/96", "::ffff:0.0.0.0/96"])
def test_r15_17_3_table_with_the_mapped_range_is_red(spelling):
    t = copy.deepcopy(committed())
    t["ranges"].append(spelling)
    assert any(spelling in p for p in guard.table_problems(t))


def test_load_table_validates():
    assert guard.load_table() == tuple(committed()["ranges"])
    with pytest.raises(ValueError):
        guard.validate_table({"format": guard.TABLE_FORMAT, "python": "3.12", "dropped": [], "ranges": ["nope"],
                              "source": "x"})
    with pytest.raises(ValueError):
        guard.validate_table({"format": "other/9", "python": "3.12", "dropped": [], "ranges": [], "source": "x"})


# --- R9-A6: the decider's address wall uses front.refused_address -------------------------------------------------

@pytest.mark.parametrize("answer", ["64:ff9b::7f00:1", "2002:7f00:1::1", "2001:0:7f00:1::1"])
def test_r9_a6_embedded_ipv4_answers_wall(answer):
    assert guard.address_wall([answer]) == "non_public_address"


@pytest.mark.parametrize("answers,wall", [
    (["93.184.215.14"], None),
    (["2606:2800:21f:cb07:6820:80da:af6b:8b2c"], None),
    (["93.184.215.14", "10.0.0.1"], "non_public_address"),       # ANY answer refused walls the host
    (["2606:4700::1%en0"], "non_public_address"),                # a scope id: the Python decider's rule
    (["::ffff:8.8.8.8"], "non_public_address"),                  # front refuses every IPv4-mapped answer
    (["64:ff9b::808:808"], None),                                # NAT64 judged by the IPv4 it embeds
    (["not-an-address"], "non_public_address"),
])
def test_r9_a6_address_wall(answers, wall):
    assert guard.address_wall(answers) == wall


def test_expected_dial_refusal_translates_the_mapped_form():
    """The one translation the generated table makes: an IPv4-mapped answer is dialed as the IPv4 it carries, so
    at dial its verdict is that IPv4's (front's own rule refuses every mapped answer, at the decider)."""
    assert guard.expected_dial_refusal("::ffff:8.8.8.8") is False
    assert guard.expected_dial_refusal("::ffff:10.0.0.1") is True
    assert guard.expected_dial_refusal("10.0.0.1") is True
    assert guard.expected_dial_refusal("8.8.8.8") is False


def test_r9_a6_no_answer_is_the_callers_resolution_failure():
    """An empty answer is a failed resolution, not an address verdict: the caller denies it on its own path."""
    with pytest.raises(ValueError):
        guard.address_wall([])


